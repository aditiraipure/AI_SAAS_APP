import { clerkClient } from "@clerk/express";
import mongoose from "mongoose";
import Creation from "../models/creationModel.js";
import User from "../models/userModel.js";

/**
 * Get the authenticated user's profile and verified billing plan
 * GET /api/user/profile
 */
export const getUserProfile = async (req, res) => {
  try {
    return res.status(200).json({
      success: true,
      userId: req.userId,
      userName: req.userName,
      plan: req.plan || "free",
      isPremium: req.isPremium || false,
      freeUsage: req.dbUser?.freeUsage || 0,
    });
  } catch (error) {
    console.error("Error fetching user profile:", error.message);
    return res.status(500).json({
      success: false,
      message: "Internal server error fetching user profile",
      error: error.message,
    });
  }
};

/**
 * Get all creations generated by the authenticated user
 * GET /api/user/creations
 */
export const getUserCreations = async (req, res) => {
  try {
    const { userId } = req;

    if (!userId) {
      return res.status(401).json({
        success: false,
        message: "Unauthorized. User ID not found.",
      });
    }

    const creations = await Creation.find({ userId }).sort({ createdAt: -1 });

    return res.status(200).json({
      success: true,
      message: "User creations retrieved successfully",
      creations,
      plan: req.plan || "free",
      isPremium: req.isPremium || false,
      freeUsage: req.dbUser?.freeUsage || 0,
    });
  } catch (error) {
    console.error("Error fetching user creations:", error.message);
    return res.status(500).json({
      success: false,
      message: "Internal server error fetching user creations",
      error: error.message,
    });
  }
};

/**
 * Get all published (community) creations with resolved creator names
 * GET /api/user/published-creations
 */
export const getPublishedCreations = async (req, res) => {
  try {
    const rawCreations = await Creation.find({ publish: true })
      .sort({ createdAt: -1 })
      .lean();

    // Cache user lookups in a map to avoid repeated queries
    const userIds = [
      ...new Set(rawCreations.map((c) => c.userId).filter(Boolean)),
    ];
    const localUsers = await User.find({ userId: { $in: userIds } }).lean();
    const userMap = new Map(
      localUsers.map((u) => [u.userId, u.name || u.email]),
    );

    const enrichedCreations = await Promise.all(
      rawCreations.map(async (creation) => {
        let displayName =
          creation.userName &&
          creation.userName !== "Anonymous" &&
          creation.userName !== "QuickAI Creator"
            ? creation.userName
            : userMap.get(creation.userId);

        if (!displayName || displayName === "QuickAI Creator") {
          try {
            const clerkUser = await clerkClient.users.getUser(creation.userId);
            displayName =
              clerkUser?.fullName ||
              [clerkUser?.firstName, clerkUser?.lastName]
                .filter(Boolean)
                .join(" ") ||
              clerkUser?.username ||
              clerkUser?.emailAddresses?.[0]?.emailAddress?.split("@")[0] ||
              "Creator";

            if (displayName) {
              userMap.set(creation.userId, displayName);
              // Backfill name in DB
              await Creation.updateOne(
                { _id: creation._id },
                { userName: displayName },
              ).catch(() => {});
            }
          } catch {
            displayName = userMap.get(creation.userId) || "Community Creator";
          }
        }

        return {
          ...creation,
          userName: displayName || "Community Creator",
        };
      }),
    );

    return res.status(200).json({
      success: true,
      message: "Published creations retrieved successfully",
      creations: enrichedCreations,
    });
  } catch (error) {
    console.error("Error fetching published creations:", error.message);
    return res.status(500).json({
      success: false,
      message: "Internal server error fetching published creations",
      error: error.message,
    });
  }
};

/**
 * Toggle like/unlike on a creation
 * POST /api/user/creations/:creationId/like
 */
export const toggleLikeCreation = async (req, res) => {
  try {
    const { userId } = req;
    const { creationId } = req.params;

    if (!userId) {
      return res.status(401).json({
        success: false,
        message: "Unauthorized. User ID not found.",
      });
    }

    if (!creationId) {
      return res.status(400).json({
        success: false,
        message: "Creation ID is required",
      });
    }

    if (!mongoose.Types.ObjectId.isValid(creationId)) {
      return res.status(400).json({
        success: false,
        message: "Invalid creation ID format",
      });
    }

    const creation = await Creation.findById(creationId);

    if (!creation) {
      return res.status(404).json({
        success: false,
        message: "Creation not found",
      });
    }

    // Ensure likes is an array
    if (!Array.isArray(creation.likes)) {
      creation.likes = [];
    }

    const alreadyLiked = creation.likes.includes(userId);

    if (alreadyLiked) {
      creation.likes = creation.likes.filter((id) => id !== userId);
    } else {
      creation.likes.push(userId);
    }

    await creation.save();

    return res.status(200).json({
      success: true,
      message: alreadyLiked ? "Creation unliked" : "Creation liked",
      likes: creation.likes,
      likesCount: creation.likes.length,
      isLiked: !alreadyLiked,
      creation,
    });
  } catch (error) {
    console.error("Error toggling like on creation:", error.message);
    return res.status(500).json({
      success: false,
      message: "Internal server error toggling creation like",
      error: error.message,
    });
  }
};
