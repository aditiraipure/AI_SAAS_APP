import express from "express";
import {
  getPublishedCreations,
  getUserCreations,
  getUserProfile,
  toggleLikeCreation,
} from "../controllers/usercontroller.js";
import { auth } from "../middleware/auth.js";

const userRouter = express.Router();

/**
 * @openapi
 * /api/user/profile:
 *   get:
 *     summary: Get authenticated user's profile and verified billing plan
 *     description: Retrieves the authenticated user's name, plan, premium status, and usage.
 *     tags:
 *       - User & Creations
 *     security:
 *       - BearerAuth: []
 *     responses:
 *       200:
 *         description: User profile and plan retrieved successfully
 *       401:
 *         description: Unauthorized
 */
userRouter.get("/profile", auth, getUserProfile);
userRouter.get("/plan", auth, getUserProfile);

/**
 * @openapi
 * /api/user/creations:
 *   get:
 *     summary: Get all creations for the logged-in user
 *     description: Retrieves a list of creations generated by the authenticated user, ordered from newest to oldest.
 *     tags:
 *       - User & Creations
 *     security:
 *       - BearerAuth: []
 *     responses:
 *       200:
 *         description: User creations retrieved successfully
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *               properties:
 *                 success:
 *                   type: boolean
 *                   example: true
 *                 message:
 *                   type: string
 *                   example: "User creations retrieved successfully"
 *                 creations:
 *                   type: array
 *                   items:
 *                     type: object
 *                     properties:
 *                       _id:
 *                         type: string
 *                         example: "67cb1a48c909e44f83bfa991"
 *                       userId:
 *                         type: string
 *                         example: "user_2yMX02PRbyMtQK6PebpjnxvRNIA"
 *                       prompt:
 *                         type: string
 *                         example: "Write an article about AI"
 *                       content:
 *                         type: string
 *                         example: "## Artificial Intelligence\n\n..."
 *                       type:
 *                         type: string
 *                         example: "article"
 *                       publish:
 *                         type: boolean
 *                         example: false
 *                       likes:
 *                         type: array
 *                         items:
 *                           type: string
 *                         example: []
 *                       createdAt:
 *                         type: string
 *                         format: date-time
 *                         example: "2025-07-01T11:07:51.312Z"
 *                       updatedAt:
 *                         type: string
 *                         format: date-time
 *                         example: "2025-07-01T11:07:51.312Z"
 *       401:
 *         description: Unauthorized / Missing Clerk session token
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/ErrorResponse'
 *       500:
 *         description: Internal server error
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/ErrorResponse'
 */
userRouter.get("/creations", auth, getUserCreations);

/**
 * @openapi
 * /api/user/published-creations:
 *   get:
 *     summary: Get all public / published community creations
 *     description: Retrieves all creations marked as published by users across the community, sorted from newest to oldest.
 *     tags:
 *       - User & Creations
 *     security:
 *       - BearerAuth: []
 *     responses:
 *       200:
 *         description: Published creations retrieved successfully
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *               properties:
 *                 success:
 *                   type: boolean
 *                   example: true
 *                 message:
 *                   type: string
 *                   example: "Published creations retrieved successfully"
 *                 creations:
 *                   type: array
 *                   items:
 *                     type: object
 *                     properties:
 *                       _id:
 *                         type: string
 *                         example: "67cb1a48c909e44f83bfa991"
 *                       userId:
 *                         type: string
 *                         example: "user_2yMX02PRbyMtQK6PebpjnxvRNIA"
 *                       prompt:
 *                         type: string
 *                         example: "A futuristic cyberpunk city in 2050"
 *                       content:
 *                         type: string
 *                         example: "https://res.cloudinary.com/demo/image/upload/v1/sample.jpg"
 *                       type:
 *                         type: string
 *                         example: "image"
 *                       publish:
 *                         type: boolean
 *                         example: true
 *                       likes:
 *                         type: array
 *                         items:
 *                           type: string
 *                         example: ["user_2yMX02PRbyMtQK6PebpjnxvRNIA"]
 *                       createdAt:
 *                         type: string
 *                         format: date-time
 *                       updatedAt:
 *                         type: string
 *                         format: date-time
 *       401:
 *         description: Unauthorized / Missing Clerk session token
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/ErrorResponse'
 *       500:
 *         description: Internal server error
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/ErrorResponse'
 */
userRouter.get("/published-creations", auth, getPublishedCreations);

/**
 * @openapi
 * /api/user/creations/{creationId}/like:
 *   post:
 *     summary: Toggle like/unlike on a creation
 *     description: Toggles the like state of the authenticated user on a specific creation. Prevents duplicate likes.
 *     tags:
 *       - User & Creations
 *     security:
 *       - BearerAuth: []
 *     parameters:
 *       - in: path
 *         name: creationId
 *         required: true
 *         schema:
 *           type: string
 *         description: MongoDB ObjectId of the creation
 *         example: "67cb1a48c909e44f83bfa991"
 *     responses:
 *       200:
 *         description: Like status updated successfully
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *               properties:
 *                 success:
 *                   type: boolean
 *                   example: true
 *                 message:
 *                   type: string
 *                   example: "Creation liked"
 *                 likes:
 *                   type: array
 *                   items:
 *                     type: string
 *                   example: ["user_2yMX02PRbyMtQK6PebpjnxvRNIA"]
 *                 likesCount:
 *                   type: integer
 *                   example: 1
 *                 isLiked:
 *                   type: boolean
 *                   example: true
 *                 creation:
 *                   type: object
 *       400:
 *         description: Invalid or missing creation ID
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/ErrorResponse'
 *       401:
 *         description: Unauthorized / Missing Clerk session token
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/ErrorResponse'
 *       404:
 *         description: Creation not found
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/ErrorResponse'
 *       500:
 *         description: Internal server error
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/ErrorResponse'
 */
userRouter.post("/creations/:creationId/like", auth, toggleLikeCreation);

export default userRouter;
